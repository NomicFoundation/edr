    /// Counter fixture with its solc AST replaced by a hand-written
    /// `debugSymbols` table.
    fn counter_build_info(compiler_version: &str) -> (serde_json::Value, serde_json::Value) {
        let content = include_str!("../../fixtures/sources/Counter.sol");
        let mut input: serde_json::Value =
            serde_json::from_str(include_str!("../../fixtures/solx_compiler_input.json")).unwrap();
        input["sources"]["Counter.sol"]["content"] = json!(content);

        let mut output: serde_json::Value =
            serde_json::from_str(include_str!("../../fixtures/solx_compiler_output.json")).unwrap();
        let source = output["sources"]["Counter.sol"].as_object_mut().unwrap();
        source.remove("ast");
        source.insert(
            "debugSymbols".to_string(),
            json!({
                "contracts": [{
                    "name": "Counter", "kind": "contract", "abstract": false,
                    "range": range(content, "contract Counter", "\n}"),
                    "bases": [base("Counter.sol", "Counter")],
                    "functions": [
                        function(
                            "count", "getter", "external", "view", Some("count()"),
                            range(content, "uint256 public count", ";"),
                        ),
                        function(
                            "set", "function", "public", "nonpayable", Some("set(uint256)"),
                            range(content, "function set", "\n  }"),
                        ),
                        function(
                            "_checkPositive", "function", "internal", "pure", None,
                            range(content, "function _checkPositive", "\n  }"),
                        ),
                    ],
                }],
                "spans": [
                    [0, content.len()],
                    range(content, "contract Counter", "\n}"),
                    range(content, "function _checkPositive", "\n  }"),
                    range(content, "require(", ";"),
                ],
            }),
        );

        let build_info = json!({
            "_format": "hh-sol-build-info-1",
            "id": "slang-counter",
            "solcVersion": compiler_version,
            "solcLongVersion": compiler_version,
            "compilerType": "slang",
            "input": input,
        });
        let build_info_output = json!({
            "_format": "hh-sol-build-info-output-1",
            "id": "slang-counter",
            "output": output,
        });
        (build_info, build_info_output)
    }

    fn assert_counter_decodes(contracts: &[IdentifiedContract]) {
        assert_eq!(contracts.len(), 2, "creation and runtime bytecode");

        let runtime = contracts
            .iter()
            .find(|contract| !contract.contract_metadata.is_deployment)
            .unwrap();
        assert_eq!(runtime.contract_metadata.contract.read().name, "Counter");

        let require_line = (0..runtime.contract_metadata.normalized_code.len() as u32)
            .filter_map(|pc| runtime.contract_metadata.get_instruction(pc).ok())
            .filter_map(|instruction| instruction.location.as_ref())
            .find(|location| location.get_starting_line_number().unwrap() == 13)
            .expect("an instruction maps to the require on line 13");
        let function = require_line.get_containing_function().unwrap().unwrap();
        assert_eq!(function.name, "_checkPositive");
        assert!(
            require_line.length > 0,
            "length comes from debugSymbols spans"
        );
    }

    #[test]
    fn slang_compiler_type_round_trips_through_build_info_parsing() {
        // A slang compiler version, below the minimum solc version.
        let (build_info, build_info_output) = counter_build_info("0.1.0");
        let mut with_output = build_info.clone();
        with_output["output"] = build_info_output["output"].clone();
        let with_output = with_output.to_string();
        let build_info = build_info.to_string();
        let build_info_output = build_info_output.to_string();

        let combined = BuildInfoConfig::parse_from_buffers(BuildInfoConfigWithBuffers {
            build_infos: Some(BuildInfoBuffers::WithOutput(vec![with_output.as_bytes()])),
            ignore_contracts: None,
        })
        .unwrap();
        assert_counter_decodes(&combined.identified_contracts);

        let separate = BuildInfoConfig::parse_from_buffers(BuildInfoConfigWithBuffers {
            build_infos: Some(BuildInfoBuffers::SeparateInputOutput(vec![
                BuildInfoBufferSeparateOutput {
                    build_info: build_info.as_bytes(),
                    output: build_info_output.as_bytes(),
                },
            ])),
            ignore_contracts: None,
        })
        .unwrap();
        assert_counter_decodes(&separate.identified_contracts);
    }
