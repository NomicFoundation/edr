/// Per-source symbol table emitted by the slang compiler under the
/// `debugSymbols` output selection.
#[derive(Clone, Debug, Default, PartialEq, Eq, Deserialize, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct DebugSymbols {
    #[serde(default)]
    pub contracts: Vec<ContractSymbol>,
    #[serde(default)]
    pub free_functions: Vec<FunctionSymbol>,
    /// Range of every syntax node in the source.
    #[serde(default)]
    pub spans: Vec<SourceRange>,
}

/// A `[byteOffset, byteLength]` range into the source content.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Deserialize, Serialize)]
#[serde(from = "[u32; 2]", into = "[u32; 2]")]
pub struct SourceRange {
    pub offset: u32,
    pub length: u32,
}

impl From<[u32; 2]> for SourceRange {
    fn from([offset, length]: [u32; 2]) -> Self {
        Self { offset, length }
    }
}

impl From<SourceRange> for [u32; 2] {
    fn from(range: SourceRange) -> Self {
        [range.offset, range.length]
    }
}

#[derive(Clone, Debug, PartialEq, Eq, Deserialize, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ContractSymbol {
    pub name: String,
    pub kind: ContractSymbolKind,
    #[serde(rename = "abstract", default)]
    pub is_abstract: bool,
    pub range: SourceRange,
    /// C3 linearization, the contract itself first.
    #[serde(default)]
    pub bases: Vec<ContractRef>,
    /// The contract's own members; inherited ones are resolved through
    /// `bases`.
    #[serde(default)]
    pub functions: Vec<FunctionSymbol>,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Deserialize, Serialize)]
#[serde(rename_all = "camelCase")]
pub enum ContractSymbolKind {
    Contract,
    Interface,
    Library,
    #[serde(other)]
    Unknown,
}

/// A contract identified by its source path and name.
#[derive(Clone, Debug, PartialEq, Eq, Deserialize, Serialize)]
pub struct ContractRef {
    pub path: String,
    pub name: String,
}

#[derive(Clone, Debug, PartialEq, Eq, Deserialize, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct FunctionSymbol {
    pub name: String,
    pub kind: FunctionSymbolKind,
    pub visibility: Option<String>,
    pub mutability: Option<String>,
    /// Hex-encoded 4-byte selector of externally visible functions and
    /// getters.
    pub selector: Option<String>,
    pub range: SourceRange,
    #[serde(default = "default_implemented")]
    pub implemented: bool,
}

fn default_implemented() -> bool {
    true
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Deserialize, Serialize)]
#[serde(rename_all = "camelCase")]
pub enum FunctionSymbolKind {
    Function,
    Constructor,
    Fallback,
    Receive,
    Modifier,
    Getter,
    Free,
    #[serde(other)]
    Unknown,
}

/// Parses the compiler metadata generated by the slang compiler as a single
/// JSON file, extracts the contained compiler metadata, and returns a vector
/// of identified contracts.
pub fn parse_slang_compiler_metadata(
    metadata: impl JsonSource,
) -> Result<Vec<IdentifiedContract>, CompilerMetadataParseError> {
    let BuildInfoWithOutput {
        _format,
        id: _,
        solc_version,
        solc_long_version: _,
        input,
        output,
    } = metadata.parse_json::<BuildInfoWithOutput<SolxBytecode>>()?;

    extract_slang_contract_metadata(solc_version, input, output)
        .map_err(CompilerMetadataParseError::from)
}

/// Parses the compiler metadata generated by the slang compiler as two
/// separate JSON files (one for the input and one for the output), extracts
/// the contained compiler metadata, and returns a vector of identified
/// contracts.
pub fn parse_split_slang_compiler_metadata(
    input: impl JsonSource,
    output: impl JsonSource,
) -> Result<Vec<IdentifiedContract>, SplitCompilerMetadataParseError> {
    let BuildInfo {
        _format,
        id: input_id,
        solc_version,
        solc_long_version: _,
        input,
    } = input.parse_json::<BuildInfo>()?;

    let BuildInfoOutput {
        _format,
        id: output_id,
        output,
    } = output.parse_json::<BuildInfoOutput<SolxBytecode>>()?;

    if input_id != output_id {
        return Err(SplitCompilerMetadataParseError::IdMismatch {
            input_id,
            output_id: output_id.clone(),
        });
    }

    extract_slang_contract_metadata(solc_version, input, output)
        .map_err(SplitCompilerMetadataParseError::from)
}

/// Extracts [`IdentifiedContract`]s from the provided slang compiler input
/// and output.
///
/// `compiler_version` is not checked against the minimum supported solc
/// version: the slang compiler is versioned independently of solc.
pub fn extract_slang_contract_metadata(
    compiler_version: String,
    compiler_input: CompilerInput,
    compiler_output: CompilerOutput<SolxBytecode>,
) -> Result<Vec<IdentifiedContract>, ContractMetadataExtractionError> {
    let Some(build_model) = slang_build_model(compiler_input, &compiler_output)? else {
        return Ok(Vec::new());
    };

    identify_contracts(compiler_version, build_model, &compiler_output)
}

/// Builds the model from every source's `debugSymbols`, or returns `None`
/// when a source lacks them.
pub(crate) fn slang_build_model(
    compiler_input: CompilerInput,
    compiler_output: &CompilerOutput<SolxBytecode>,
) -> anyhow::Result<Option<SolxBuildModel>> {
    let mut sources = Vec::with_capacity(compiler_output.sources.len());
    for (source_name, source) in &compiler_output.sources {
        let Some(debug_symbols) = source.debug_symbols.as_ref() else {
            log::warn!(
                "The slang compiler output for {source_name} has no debugSymbols: it was \
                 produced without the \"debugSymbols\" output selection. Stack traces are \
                 unavailable for this compilation."
            );
            return Ok(None);
        };

        let content = match compiler_input.sources.get(source_name) {
            Some(input_source) => input_source.content.clone(),
            None => bail!("Compiler input missing source for {source_name}"),
        };
        let file = Arc::new(RwLock::new(SourceFile::new(source_name.clone(), content)));

        sources.push((source_name.as_str(), source.id, file, debug_symbols));
    }

    let mut contracts: IndexMap<(&str, &str), Arc<RwLock<Contract>>> = IndexMap::new();
    let mut ast_spans = HashMap::with_capacity(sources.len());

    for (source_name, file_id, file, debug_symbols) in &sources {
        let mut functions = Vec::new();

        for contract_symbol in &debug_symbols.contracts {
            let kind = match contract_symbol.kind {
                ContractSymbolKind::Contract => ContractKind::Contract,
                ContractSymbolKind::Library => ContractKind::Library,
                ContractSymbolKind::Interface | ContractSymbolKind::Unknown => continue,
            };

            let contract_abi = compiler_output
                .contracts
                .get(*source_name)
                .and_then(|contracts| contracts.get(&contract_symbol.name))
                .map(|contract| contract.abi.as_slice());

            let mut contract = Contract::new(
                contract_symbol.name.clone(),
                kind,
                SourceLocation::new(
                    file,
                    contract_symbol.range.offset,
                    contract_symbol.range.length,
                ),
            );

            for function_symbol in &contract_symbol.functions {
                let function =
                    contract_function(function_symbol, file, Some(&contract.name), contract_abi)
                        .with_context(|| {
                            format!(
                                "Invalid debugSymbols entry {}.{} in {source_name}",
                                contract_symbol.name, function_symbol.name
                            )
                        })?;

                if let Some(function) = function {
                    contract.add_local_function(function.clone())?;
                    functions.push(function);
                }
            }

            contracts.insert(
                (*source_name, contract_symbol.name.as_str()),
                Arc::new(RwLock::new(contract)),
            );
        }

        for function_symbol in &debug_symbols.free_functions {
            let function =
                contract_function(function_symbol, file, None, None).with_context(|| {
                    format!(
                        "Invalid debugSymbols entry {} in {source_name}",
                        function_symbol.name
                    )
                })?;
            functions.extend(function);
        }

        file.write().finalize(functions.into_boxed_slice());

        let mut spans: Vec<(u32, u32)> = debug_symbols
            .spans
            .iter()
            .map(|range| (range.offset, range.length))
            .collect();
        spans.sort_unstable();
        spans.dedup();
        ast_spans.insert(*file_id, spans);
    }

    for (source_name, _, _, debug_symbols) in &sources {
        for contract_symbol in &debug_symbols.contracts {
            let key = (*source_name, contract_symbol.name.as_str());
            let Some(contract) = contracts.get(&key) else {
                continue;
            };
            let mut contract = contract.write();

            for base in &contract_symbol.bases {
                let base_key = (base.path.as_str(), base.name.as_str());
                if base_key == key {
                    continue;
                }
                // Interfaces are not modelled.
                let Some(base_contract) = contracts.get(&base_key) else {
                    continue;
                };
                contract.add_next_linearized_base_contract(&base_contract.read())?;
            }
        }
    }

    // Contracts absent from the output's `contracts` only serve as bases.
    let contract_id_to_contract = (0u32..)
        .zip(
            contracts
                .into_iter()
                .filter_map(|((file, name), contract)| {
                    compiler_output
                        .contracts
                        .get(file)
                        .is_some_and(|contracts| contracts.contains_key(name))
                        .then_some(contract)
                }),
        )
        .collect();

    let file_id_to_source_file = sources
        .into_iter()
        .map(|(_, file_id, file, _)| (file_id, file))
        .collect();

    Ok(Some(SolxBuildModel::from_parts(
        CompiledContractsAndFiles {
            contract_id_to_contract,
            file_id_to_source_file,
        },
        ast_spans,
    )))
}

fn contract_function(
    symbol: &FunctionSymbol,
    file: &Arc<RwLock<SourceFile>>,
    contract_name: Option<&str>,
    contract_abi: Option<&[ContractAbiEntry]>,
) -> anyhow::Result<Option<Arc<ContractFunction>>> {
    let function_type = match symbol.kind {
        FunctionSymbolKind::Function => ContractFunctionType::Function,
        FunctionSymbolKind::Constructor => ContractFunctionType::Constructor,
        FunctionSymbolKind::Fallback => ContractFunctionType::Fallback,
        FunctionSymbolKind::Receive => ContractFunctionType::Receive,
        FunctionSymbolKind::Modifier => ContractFunctionType::Modifier,
        FunctionSymbolKind::Getter => ContractFunctionType::Getter,
        FunctionSymbolKind::Free => ContractFunctionType::FreeFunction,
        FunctionSymbolKind::Unknown => return Ok(None),
    };

    let location = SourceLocation::new(file, symbol.range.offset, symbol.range.length);
    let contract_name = contract_name.map(str::to_owned);

    if function_type == ContractFunctionType::Modifier {
        return Ok(Some(Arc::new(ContractFunction {
            name: symbol.name.clone(),
            r#type: function_type,
            location,
            contract_name,
            visibility: None,
            is_payable: None,
            selector: RwLock::new(None),
            param_types: None,
        })));
    }

    if !symbol.implemented {
        return Ok(None);
    }

    let visibility = symbol
        .visibility
        .as_deref()
        .and_then(|visibility| ContractFunctionVisibility::from_str(visibility).ok())
        .unwrap_or_default();

    let has_selector = match function_type {
        ContractFunctionType::Function => matches!(
            visibility,
            ContractFunctionVisibility::Public | ContractFunctionVisibility::External
        ),
        ContractFunctionType::Getter => true,
        _ => false,
    };

    let selector = if has_selector {
        let selector = symbol
            .selector
            .as_deref()
            .context("Externally visible function has no selector")?;
        Some(hex::decode(selector).with_context(|| format!("Failed to decode hex: {selector:?}"))?)
    } else {
        None
    };

    let abi_entry = contract_abi.and_then(|abi| {
        let mut functions_named = abi.iter().filter(|entry| {
            entry.r#type.as_deref() == Some("function")
                && entry.name.as_deref() == Some(&symbol.name)
        });
        if function_type == ContractFunctionType::Getter {
            functions_named.next()
        } else {
            let selector = selector.as_deref()?;
            functions_named.find(|entry| {
                abi_entry_selector(entry).is_some_and(|abi_selector| abi_selector == selector)
            })
        }
    });

    Ok(Some(Arc::new(ContractFunction {
        name: symbol.name.clone(),
        r#type: function_type,
        location,
        contract_name,
        visibility: Some(visibility),
        is_payable: Some(symbol.mutability.as_deref() == Some("payable")),
        selector: RwLock::new(selector),
        param_types: abi_entry.and_then(|entry| entry.inputs.clone()),
    })))
}

fn abi_entry_selector(entry: &ContractAbiEntry) -> Option<[u8; 4]> {
    let inputs = entry
        .inputs
        .iter()
        .flatten()
        .map(|input| serde_json::from_value(input.clone()))
        .collect::<Result<Vec<alloy_json_abi::Param>, _>>()
        .ok()?;

    let function = alloy_json_abi::Function {
        name: entry.name.clone()?,
        inputs,
        outputs: Vec::new(),
        state_mutability: alloy_json_abi::StateMutability::NonPayable,
    };

    Some(function.selector().0)
}

