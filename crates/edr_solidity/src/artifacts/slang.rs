    #[test]
    fn models_local_functions() {
        let model = diamond_build_model();

        let root = contract_named(&model, "Root");
        let root = root.read();

        let set_one = root
            .get_function_from_selector(&hex::decode(selector("set(uint256)")).unwrap())
            .unwrap();
        assert_eq!(set_one.r#type, ContractFunctionType::Function);
        assert_eq!(set_one.visibility, Some(ContractFunctionVisibility::Public));
        assert_eq!(set_one.is_payable, Some(false));
        assert_eq!(set_one.param_types.as_ref().map(Vec::len), Some(1));

        let set_two = root
            .get_function_from_selector(&hex::decode(selector("set(uint256,uint256)")).unwrap())
            .unwrap();
        assert_eq!(set_two.param_types.as_ref().map(Vec::len), Some(2));
        assert_eq!(
            set_two.location.offset,
            range(A_SOL, "function set(uint256 x, uint256 y)", "\n    }").offset,
            "overloads keep their own locations"
        );

        let thing = root
            .get_function_from_selector(&hex::decode(selector("thing()")).unwrap())
            .unwrap();
        assert_eq!(thing.visibility, Some(ContractFunctionVisibility::External));

        let count = root
            .get_function_from_selector(&hex::decode(selector("count()")).unwrap())
            .unwrap();
        assert_eq!(count.r#type, ContractFunctionType::Getter);
        assert_eq!(count.is_payable, Some(false));
        assert_eq!(count.param_types.as_ref().map(Vec::len), Some(0));

        assert!(
            root.get_function_from_selector(&hex::decode(selector("todo()")).unwrap())
                .is_none(),
            "unimplemented functions are skipped"
        );
        assert!(function_containing(&model, 0, "function todo() public virtual;").is_none());

        let modifier = function_containing(&model, 0, "require(x > 0)").unwrap();
        assert_eq!(modifier.name, "onlyPositive");
        assert_eq!(modifier.r#type, ContractFunctionType::Modifier);
        assert_eq!(modifier.contract_name.as_deref(), Some("Root"));
        assert_eq!(modifier.visibility, None);
        assert_eq!(*modifier.selector.read(), None);

        let twice = function_containing(&model, 0, "return x * 2").unwrap();
        assert_eq!(twice.contract_name.as_deref(), Some("Lib"));
        assert_eq!(twice.visibility, Some(ContractFunctionVisibility::Internal));
        assert_eq!(*twice.selector.read(), None);

        let helper = function_containing(&model, 0, "return x + 1").unwrap();
        assert_eq!(helper.name, "helper");
        assert_eq!(helper.r#type, ContractFunctionType::FreeFunction);
        assert_eq!(helper.contract_name, None);

        let diamond = contract_named(&model, "Diamond");
        let diamond = diamond.read();
        let constructor = diamond.constructor.as_ref().unwrap();
        assert_eq!(constructor.r#type, ContractFunctionType::Constructor);
        assert_eq!(constructor.is_payable, Some(true));
        assert_eq!(
            diamond.fallback.as_ref().unwrap().r#type,
            ContractFunctionType::Fallback
        );
        assert_eq!(diamond.receive.as_ref().unwrap().is_payable, Some(true));
    }

    #[test]
    fn resolves_inherited_functions_in_linearization_order() {
        let model = diamond_build_model();

        let diamond = contract_named(&model, "Diamond");
        let diamond = diamond.read();
        assert_eq!(
            dispatched_to(&diamond, "todo()").as_deref(),
            Some("Diamond")
        );
        assert_eq!(
            dispatched_to(&diamond, "set(uint256)").as_deref(),
            Some("Left")
        );
        assert_eq!(
            dispatched_to(&diamond, "set(uint256,uint256)").as_deref(),
            Some("Root")
        );
        assert_eq!(dispatched_to(&diamond, "thing()").as_deref(), Some("Root"));
        assert_eq!(dispatched_to(&diamond, "count()").as_deref(), Some("Root"));

        let right = contract_named(&model, "Right");
        let right = right.read();
        assert_eq!(dispatched_to(&right, "todo()").as_deref(), Some("Right"));
        assert_eq!(
            dispatched_to(&right, "set(uint256)").as_deref(),
            Some("Root")
        );
        assert!(right.constructor.is_none());
        assert!(right.fallback.is_none());

        let left = contract_named(&model, "Left");
        assert_eq!(
            dispatched_to(&left.read(), "todo()").as_deref(),
            Some("Left")
        );
    }

    #[test]
    fn looks_up_spans_and_sources() {
        let model = diamond_build_model();

        let statement = range(A_SOL, "count = x;", ";");
        let inside_statement = statement.offset + 3;
        assert_eq!(
            model.smallest_enclosing_span(0, inside_statement),
            Some((statement.offset, statement.length))
        );

        let set_one = range(A_SOL, "function set(uint256 x) public", "\n    }");
        assert_eq!(
            model.smallest_enclosing_span(0, set_one.offset),
            Some((set_one.offset, set_one.length))
        );

        assert_eq!(
            model.smallest_enclosing_span(0, 0),
            Some((0, A_SOL.len() as u32))
        );
        assert_eq!(model.smallest_enclosing_span(0, A_SOL.len() as u32), None);
        assert_eq!(model.smallest_enclosing_span(7, 0), None);

        for (file_id, source_name) in [(0, "A.sol"), (1, "B.sol")] {
            let file = model.source_model_by_file_id(file_id).unwrap();
            assert_eq!(file.read().source_name, source_name);
            assert_eq!(model.file_id_by_name(source_name), Some(file_id));
        }
        assert!(model.source_model_by_file_id(2).is_none());
    }

