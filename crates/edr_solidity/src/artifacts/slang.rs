    fn contract_named(model: &SolxBuildModel, name: &str) -> Arc<RwLock<Contract>> {
        model
            .contracts()
            .find(|contract| contract.read().name == name)
            .unwrap_or_else(|| panic!("{name} is in the model"))
            .clone()
    }

    /// Name of the contract declaring the function `contract` dispatches
    /// `signature` to.
    fn dispatched_to(contract: &Contract, signature: &str) -> Option<String> {
        let selector = hex::decode(selector(signature)).unwrap();
        contract
            .get_function_from_selector(&selector)
            .map(|function| function.contract_name.clone().expect("contract function"))
    }

