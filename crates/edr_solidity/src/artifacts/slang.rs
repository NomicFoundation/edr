    fn range(source: &str, start: &str, end: &str) -> SourceRange {
        let offset = source.find(start).expect("start marker in source");
        let end_offset =
            offset + source[offset..].find(end).expect("end marker after start") + end.len();
        SourceRange {
            offset: offset as u32,
            length: (end_offset - offset) as u32,
        }
    }

